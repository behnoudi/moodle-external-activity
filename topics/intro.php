### چرا باید دقیق حرف بزنیم؟

هوش مصنوعی نمی‌تواند فکر تو را بخواند. او فقط کلمه‌هایی را که می‌نویسی می‌بیند. پس هرچه دقیق‌تر و روشن‌تر بگویی چه می‌خواهی، جواب بهتری می‌گیری.

**مثال ضعیف (مثل حرف زدن با غول کوته‌فکر):**
> یک داستان بنویس.

**مثال خوب:**
> یک داستان کوتاه و بامزه درباره‌ی یک سگ فضانورد بنویس که به سیاره‌ی مریخ سفر می‌کند. داستان حداکثر ۱۰۰ کلمه باشد.

می‌بینی چه فرقی دارند؟ در مثال دوم، دقیقاً مشخص کرده‌ایم:
- **چه چیزی می‌خواهیم:** یک داستان
- **درباره‌ی چه:** سگ فضانورد و سفر به مریخ
- **چه حسی داشته باشد:** بامزه
- **چقدر بلند باشد:** حداکثر ۱۰۰ کلمه

